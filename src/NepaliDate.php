    public static function convertToNepali(string $englishDate): array
    {
        try {
            $date = Carbon::parse($englishDate)->setTimezone('Asia/Kathmandu');
        } catch (\Exception $e) {
            throw new InvalidArgumentException('Invalid date format: ' . $englishDate);
        }
        
        $refDate = Carbon::parse(self::REFERENCE_AD_DATE);
        $daysDiff = $date->diffInDays($refDate);
        
        [$nepYear, $nepMonth, $nepDay] = self::REFERENCE_BS_DATE;
        
        while ($daysDiff > 0) {
            if (!isset(self::$calendarData[$nepYear])) {
                throw new InvalidArgumentException('Date out of supported range');
            }
            
            $daysInMonth = self::$calendarData[$nepYear][$nepMonth - 1];
            
            if ($daysDiff >= $daysInMonth) {
                $daysDiff -= $daysInMonth;
                $nepMonth++;
                
                if ($nepMonth > 12) {
                    $nepMonth = 1;
                    $nepYear++;
                }
            } else {
                $nepDay += $daysDiff;
                $daysDiff = 0;
            }
        }

        return [
            'year' => $nepYear,
            'month' => $nepMonth,
            'day' => $nepDay,
            'month_name_nepali' => self::$nepaliMonths[$nepMonth],
            'month_name_english' => self::$englishMonths[$nepMonth],
            'day_name' => self::$nepaliDays[$date->format('l')]
        ];
    }

    public static function format(string $englishDate, string $format = 'Y-m-d', bool $nepaliNumerals = true): string
    {
        $nepaliDate = self::convertToNepali($englishDate);
        
        $formatted = str_replace([
            'Y', 'm', 'd', 'F', 'M', 'l'
        ], [
            $nepaliDate['year'],
            str_pad($nepaliDate['month'], 2, '0', STR_PAD_LEFT),
            str_pad($nepaliDate['day'], 2, '0', STR_PAD_LEFT),
            $nepaliDate['month_name_nepali'],
            $nepaliDate['month_name_english'],
            $nepaliDate['day_name']
        ], $format);

        return $nepaliNumerals ? self::convertToNepaliNumbers($formatted) : $formatted;
    }

    public static function today(string $format = 'Y-m-d'): string
    {
        return self::format(now()->format('Y-m-d'), $format);
    }

    public static function isValidNepaliYear(int $year): bool
    {
        return isset(self::$calendarData[$year]);
    }

    public static function getSupportedYearRange(): array
    {
        $years = array_keys(self::$calendarData);
        return ['min' => min($years), 'max' => max($years)];
    }

    private static function convertToNepaliNumbers(string $text): string
    {
        return strtr($text, self::$nepaliNumbers);
    }
